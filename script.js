// ===== Language switcher =====
function setLanguage(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  localStorage.setItem("lang", lang);
}

// ===== Menu tabs =====
function initTabs() {
  const tabButtons = document.querySelectorAll(".tab-btn");
  const panels = document.querySelectorAll(".menu-panel");

  tabButtons.forEach(btn => {
    btn.addEventListener("click", () => {
      // remove active from all
      tabButtons.forEach(b => b.classList.remove("active"));
      panels.forEach(p => p.classList.remove("active"));

      // add active to clicked
      btn.classList.add("active");
      const target = document.getElementById(btn.dataset.tab);
      if (target) {
        target.classList.add("active");
      }
    });
  });
}

// ===== Fade-up animation =====
function initAnimations() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
      }
    });
  }, { threshold: 0.12 });

  document.querySelectorAll(".menu-item, .section-title, .about-text").forEach(el => {
    el.classList.add("fade-up");
    observer.observe(el);
  });
}

// ===== Initialize everything when DOM is ready =====
document.addEventListener("DOMContentLoaded", () => {
  // Language
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      setLanguage(btn.dataset.lang);
    });
  });

  const savedLang = localStorage.getItem("lang") || "bg";
  setLanguage(savedLang);

  // Tabs
  initTabs();

  // Animations
  initAnimations();
});

document.addEventListener("DOMContentLoaded", () => {
  const galleryGrid = document.getElementById("gallery-grid");
  
  if (galleryGrid) {
    fetch("gallery.json")
      .then(response => {
        if (!response.ok) throw new Error("Could not load gallery.json");
        return response.json();
      })
      .then(data => {
        galleryGrid.innerHTML = ""; // Clear placeholder comments if any
        data.forEach(item => {
          const img = document.createElement("img");
          img.src = item.src;
          img.alt = item.alt;
          img.loading = "lazy";
          galleryGrid.appendChild(img);
        });
      })
      .catch(error => console.error("Error loading gallery images:", error));
  }
});